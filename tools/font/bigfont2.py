BASE={'á':('a','´'),'à':('a','`'),'â':('a','^'),'ã':('a','~'),'é':('e','´'),'ê':('e','^'),
 'í':('i','´'),'ó':('o','´'),'ô':('o','^'),'õ':('o','~'),'ú':('u','´')}
def raster(ch,thin=None):
    if thin is None: thin=(ch.islower() or ch in 'áàâãéêíóôõúç.,:')
    if ch in BASE:
        b,a=BASE[ch];lines=[list(l) for l in S[b]]
        if b=='i': lines=[lines[0]]       # drop the dot
        ap=ACC[a]
        if b=='i': ap=[(x-1,y) for x,y in ACC[a]] if False else ACC[a]
        lines.append(ap)
        bx=0
        if b=='i': lines.append([(0,0),(0,0)]) if False else None
        lines=[[(x+ (0),y) for x,y in l] for l in lines]
    elif ch=='ç':
        lines=[list(l) for l in S['c']]+[[(2,11),(3,12)]]
    else: lines=S[ch]
    P=set()
    XS=1.0 if thin else 7/6.0                    # capitals 9 px wide, 12 rows tall (measured on the original)
    lines=[[(int(x*XS+0.5),int(y*YS+0.5)) for x,y in l] for l in lines]
    for l in lines:
        pts=l if len(l)>1 else l*2
        for (x0,y0),(x1,y1) in zip(pts,pts[1:]):
            n=max(abs(x1-x0),abs(y1-y0),1)
            for k in range(n+1):
                x=round(x0+(x1-x0)*k/n);y=round(y0+(y1-y0)*k/n)
                for dx in((0,) if thin else (0,1)):    # brush: caps 2 wide x 1 tall (thick verticals, 1 px horizontals), lowercase 1x1
                    P.add((x+dx,y))
    if not P:return P,0
    mx=min(x for x,_ in P);P={(x-mx,y) for x,y in P}
    return P,max(x for x,_ in P)+1
def pixels(text,gap=1,space=4):
    out=set();x=0;prev=None
    for ch in text:
        if ch==' ':x+=space;prev=None;continue
        P,w=raster(ch)
        if prev is not None and not (prev.islower() and ch.islower()): x+=1 if (prev.islower() or ch.islower()) else 2   # extra air next to capitals/digits, like the original
        for (px,py) in P:out.add((x+px,py))
        x+=w+gap;prev=ch
    return out,x-gap
