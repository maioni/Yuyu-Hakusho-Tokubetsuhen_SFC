def accented(base,acc,w=None):
    top,rows=G[base];w=max(len(r) for r in rows)
    a0,a1=ACC[acc][0]
    a0=a0[:w].ljust(w,'.');a1=a1[:w].ljust(w,'.')
    # lowercase top may be 3 or 0/1; accents go to rows 0,1 -> only for glyphs with top>=3 (x-height)
    pad=[a0,a1]+["."*w]*(top-2) if top>=2 else None
    return (0,pad+rows)
