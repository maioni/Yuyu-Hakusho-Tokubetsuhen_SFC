def glyph_w(ch):
    return max(len(r) for r in G[ch][1])
def layout(text,gap=1,space=3):
    cols=[];x=0
    for ch in text:
        if ch==' ': x+=space;continue
        top,rows=G[ch];w=max(len(r) for r in rows);rows=[r.ljust(w,'.') for r in rows]
        l=min((r.index('#') for r in rows if '#' in r),default=0)       # trim empty columns (kerning)
        rr=max((r.rindex('#') for r in rows if '#' in r),default=w-1)
        rows=[r[l:rr+1] for r in rows];w=rr-l+1
        cols.append((x,top,rows));x+=w+gap
    return cols,x-gap
def pixels(text,gap=1):
    cols,W=layout(text,gap);P=set()
    for x,top,rows in cols:
        for r,row in enumerate(rows):
            for c,ch in enumerate(row):
                if ch=='#':P.add((x+c,top+r))
    return P,W
